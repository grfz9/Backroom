/**
 * LIMINAL — world data model (pure data, no rendering, no DOM).
 * CONTRACT FILE: changes must be validated by the technical director (see docs/AGENTS.md).
 *
 * The world is an infinite 2.5D grid of square cells (CELL metres), streamed in chunks of
 * CHUNK×CHUNK cells. Geometry is described by:
 *   - the cell itself (open floor of some type, or a solid block),
 *   - thin walls on cell EDGES (each cell owns its North and West edges),
 *   - at most one prop per cell (pillar, furniture, vehicle part…),
 *   - at most one light fixture per cell,
 *   - a list of gameplay objects per chunk (pickups, doors, switches, notes, exits…).
 *
 * Coordinates: X = east, Z = south, Y = up. North is -Z.
 * Cell (ix, iz) covers [ix*CELL, (ix+1)*CELL) × [iz*CELL, (iz+1)*CELL) in world metres.
 * Chunk (cx, cz) holds cells ix in [cx*CHUNK, (cx+1)*CHUNK), same for z.
 * Local index inside a chunk: i = lz * CHUNK + lx.
 */

import type { ItemId } from '../sim/types';

/** Linear RGB, each component 0..1. */
export type RGB = readonly [number, number, number];

/** Floor material as far as gameplay is concerned (footstep sound, noise). */
export type SurfaceKind =
  | 'carpet'
  | 'concrete'
  | 'tile'
  | 'metal'
  | 'wood'
  | 'linoleum'
  | 'grass'
  | 'asphalt';

// ---------------------------------------------------------------------------
// Palettes. A level declares arrays of types; chunk bytes are indices into them.
// ---------------------------------------------------------------------------

export interface CellType {
  name: string;
  /** Solid block: nobody can enter, blocks sight and sound, no floor/ceiling rendered inside. */
  solid: boolean;
  /** Floor height in metres (0 = level datum; negative for pool basins, pits). Ignored if solid. */
  floorY: number;
  /** Ceiling height in metres, or null for open sky. Ignored if solid. */
  ceilY: number | null;
  /** Absolute height of the water surface, or null when dry. Water depth = waterY - floorY. */
  waterY: number | null;
  surface: SurfaceKind;
  /** Render material keys, resolved by the client theme of the level. */
  floorMat: string;
  ceilMat: string;
  /**
   * Material of vertical faces generated by this cell: the sides of a solid block as seen from
   * its open neighbours, and for an open cell the risers visible when a neighbour's floor is higher.
   */
  sideMat: string;
}

export interface WallType {
  name: string;
  /** Height of the wall top above the floor, or null = up to the ceiling. */
  height: number | null;
  /** Height of the wall bottom above the floor (0 = starts at the floor). */
  bottom: number;
  blocksMove: boolean;
  blocksSight: boolean;
  /**
   * Door-sized opening centred on the edge. The opening never blocks movement or sight by itself;
   * a 'door' object attached to the edge can close it dynamically.
   */
  opening: { width: number; height: number } | null;
  /** Render material key. */
  mat: string;
  /** Thickness in metres (defaults to WALL_THICKNESS). */
  thickness?: number;
}

export type PropCollider =
  | null
  | { shape: 'circle'; r: number }
  | { shape: 'box'; hx: number; hz: number };

export interface PropType {
  name: string;
  /** Render model key, resolved by the client theme of the level. */
  model: string;
  /** Collision footprint centred on the cell centre (before rotation). null = walk-through. */
  collider: PropCollider;
  /** Height in metres (cover: a crouched player behind a 1.2 m prop is hidden from sight). */
  height: number;
  blocksSight: boolean;
  /** How the cell's variant byte rotates the prop: none, quarter turns (variant & 3), or free angle. */
  rotate: 'none' | 'quarter' | 'free';
}

export interface LightType {
  name: string;
  /** Render model key of the fixture (neon panel, sodium lamp, exit sign…). */
  model: string;
  color: RGB;
  /** Illumination at the fixture's own cell when fully on (1 = comfortably lit). */
  intensity: number;
  /** Reach, in cells. Illumination falls to 0 at this distance. */
  radius: number;
  /** Loudness of the electrical hum of this fixture, 0..1 (0 = silent). */
  hum: number;
}

/** Light behaviour, stored in the low 2 bits of ChunkData.lightFlags. */
export const LIGHT_STEADY = 0;
/** Mostly on, with irregular flickers and short dropouts. */
export const LIGHT_FLICKER = 1;
/** Mostly off, with rare buzzing flashes. */
export const LIGHT_DYING = 2;
/** Tube is dead: fixture is visible but never lit. */
export const LIGHT_DEAD = 3;
export type LightMode = 0 | 1 | 2 | 3;

/** Placeholders for palette index 0 (meaning "nothing here"). Never read at runtime. */
export const NO_WALL: WallType = {
  name: 'none',
  height: null,
  bottom: 0,
  blocksMove: false,
  blocksSight: false,
  opening: null,
  mat: '',
};
export const NO_PROP: PropType = {
  name: 'none',
  model: '',
  collider: null,
  height: 0,
  blocksSight: false,
  rotate: 'none',
};
export const NO_LIGHT: LightType = {
  name: 'none',
  model: '',
  color: [0, 0, 0],
  intensity: 0,
  radius: 0,
  hum: 0,
};

// ---------------------------------------------------------------------------
// Chunks
// ---------------------------------------------------------------------------

/**
 * One generated chunk. All arrays have CHUNK*CHUNK entries, index = lz*CHUNK + lx.
 * A chunk is a pure function of (level, seed, cx, cz): it is never mutated after generation.
 * Dynamic state (opened doors, taken pickups…) lives in the simulation, not here.
 */
export interface ChunkData {
  readonly cx: number;
  readonly cz: number;
  /** Cell type id → LevelDef.cells. By convention id 0 is the level's default solid block. */
  readonly cell: Uint8Array;
  /** Wall type id on the NORTH edge of each cell (0 = no wall) → LevelDef.walls. */
  readonly wallN: Uint8Array;
  /** Wall type id on the WEST edge of each cell (0 = no wall) → LevelDef.walls. */
  readonly wallW: Uint8Array;
  /** Prop type id (0 = none) → LevelDef.props. */
  readonly prop: Uint8Array;
  /** Light type id (0 = none) → LevelDef.lights. */
  readonly light: Uint8Array;
  /** bits 0-1: LightMode. bits 2-5: power group (0 = always powered, 1..15 = needs LevelState power bit). */
  readonly lightFlags: Uint8Array;
  /** Uniform random byte per cell, for visual variety (stains, prop rotation, texture offsets). */
  readonly variant: Uint8Array;
  /** Zone id per cell (0 = default). Meaning is per level (dark zone, safe room, exit room…). */
  readonly zone: Uint8Array;
  /** Gameplay objects whose anchor position lies in this chunk. */
  readonly objects: readonly WorldObjectDef[];
}

/** Reference to a cell edge. Only N and W edges are canonical (dir 0 or 3). */
export interface EdgeRef {
  ix: number;
  iz: number;
  dir: 0 | 3;
}

// ---------------------------------------------------------------------------
// Gameplay objects (static definition, generated with the chunk)
// ---------------------------------------------------------------------------

export type ObjectKind =
  /** Press E to take `item`. */
  | 'pickup'
  /** Press E to read lore `note`. */
  | 'note'
  /** Sits in the opening of `edge`. state: 0 closed, 1 open, 2 locked (needs `item` or a script). */
  | 'door'
  /** Generic thing to use (lever, valve, phone, breaker, button). state: 0/1 or script-defined. */
  | 'usable'
  /** Accepts `item` (fuse box, lock). state = number of items inserted. */
  | 'socket'
  /** Opens the code UI on the client; the level script validates the code. */
  | 'keypad'
  /** Level exit. The level script decides when it is open. */
  | 'exit'
  /** Hiding spot (locker, wardrobe, under a desk). */
  | 'hide'
  /** Invisible volume: fires a script event when a player enters `radius`. */
  | 'trigger'
  /** Non-interactive visual marker (wall arrow, sign). */
  | 'marker';

export interface WorldObjectDef {
  /**
   * Unique and deterministic for a given (level, seed). Generated objects use
   * `${cx}_${cz}_${n}`; hand-built ones use a readable name (e.g. 'elevator_fusebox').
   */
  id: string;
  kind: ObjectKind;
  /** Anchor position in world metres (y = height of the object's base). */
  x: number;
  y: number;
  z: number;
  /** Rotation around Y in radians. */
  yaw: number;
  /** Render model key ('' = invisible), resolved by the client theme. */
  model: string;
  /** Hook name used by the level script (e.g. 'valve_a'). */
  tag?: string;
  /** pickup: item given. socket: item accepted. door: item that unlocks it. */
  item?: ItemId;
  /** door: the edge whose opening this door closes. */
  edge?: EdgeRef;
  /** note: lore entry id. */
  note?: string;
  /** Interaction / trigger radius override, in metres. */
  radius?: number;
  /** usable: seconds the player must hold the interact key (0 or undefined = instant). */
  hold?: number;
  /** Initial state value (default 0). */
  initial?: number;
  /** Free-form extra data for the level script and the renderer. */
  data?: Readonly<Record<string, number | string>>;
}

// ---------------------------------------------------------------------------
// Query results
// ---------------------------------------------------------------------------

/** A light fixture resolved to world space. */
export interface Fixture {
  ix: number;
  iz: number;
  /** World position of the fixture (cell centre, at ceiling or mount height). */
  x: number;
  y: number;
  z: number;
  type: LightType;
  mode: LightMode;
  /** Power group 0..15 (0 = always powered). */
  group: number;
  /** Per-fixture random seed driving its flicker pattern. */
  seed: number;
}

export interface RayHit {
  /** Hit position. */
  x: number;
  y: number;
  z: number;
  /** Distance from the ray origin, in metres. */
  dist: number;
  /** Surface normal on the XZ plane (unit). */
  nx: number;
  nz: number;
  what: 'wall' | 'solid' | 'prop' | 'door';
}

export interface MoveResult {
  x: number;
  z: number;
  /** True if the motion was clipped by an obstacle. */
  hit: boolean;
  /** Normal of the last obstacle touched (0,0 if none). */
  nx: number;
  nz: number;
}
